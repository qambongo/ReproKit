#!/usr/bin/env bash
# Rebuilds inpage.js (rrweb recorder + capture-core) and copies vendor files.
# Requires: npm install rrweb@2 rrweb-player@2 in ./node_modules (or set NM).
set -euo pipefail
cd "$(dirname "$0")"
NM="${NM:-node_modules}"
{
  echo "/* ReproKit in-page recorder. GENERATED by build.sh from src/capture-core.js + rrweb (MIT). */"
  echo "(function(){"
  echo "if (window.__reprokitActive) return;"
  echo "try { Object.defineProperty(window, '__reprokitActive', { value: true }); } catch (_) { return; }"
  echo "var __rkScope = {};"
  echo "(function(define, exports, module){"
  cat "$NM/rrweb/dist/rrweb.umd.min.cjs" | sed '/^\/\/# sourceMappingURL/d'
  echo "}).call(__rkScope, undefined, undefined, undefined);"
  cat src/capture-core.js
  echo "})();"
} > inpage.js
sed '/^\/\/# sourceMappingURL/d' "$NM/rrweb-player/dist/rrweb-player.umd.min.cjs" > vendor/rrweb-player.js
sed '/sourceMappingURL/d' "$NM/rrweb-player/dist/style.min.css" > vendor/rrweb-player.css
echo "Built inpage.js ($(wc -c < inpage.js) bytes)"
